//! Static files, embedded into the binary.
//!
//! `build.rs` minifies the stylesheet and the scripts before.
//!
//! Each file is served under a URL with a hash of its content, such as
//! `/assets/style.0123456789abcdef.css`, so browsers may cache it forever and
//! still get changes immediately. The old URLs of the WordPress images redirect
//! to them, as other sites and search engines still link to those.

use crate::delivery::cached::{CachePolicy, CachedResponse, Compression, content_hash};
use axum::http::StatusCode;
use std::collections::HashMap;
use std::sync::Arc;

/// The stylesheet of all pages.
pub(crate) const STYLESHEET: &str = "style.css";
/// The visual editor of the login area.
pub(crate) const EDITOR_SCRIPT: &str = "editor.js";
/// Starts the Matomo tracking.
pub(crate) const ANALYTICS_SCRIPT: &str = "analytics.js";
/// Reloads pages in the development mode.
pub(crate) const LIVE_RELOAD_SCRIPT: &str = "live-reload.js";
/// The favicon.
pub(crate) const ICON_32: &str = "images/cropped-Logo-und-Favicon-32x32.png";
/// The icon for iOS home screens.
pub(crate) const ICON_180: &str = "images/cropped-Logo-und-Favicon-180x180.png";
/// The icon for Android home screens.
pub(crate) const ICON_192: &str = "images/cropped-Logo-und-Favicon-192x192.png";
/// The tile for Windows start menus.
pub(crate) const ICON_270: &str = "images/cropped-Logo-und-Favicon-270x270.png";

/// The URL prefix of the old WordPress uploads.
const LEGACY_UPLOADS: &str = "/wp-content/uploads/2015/09/";

/// The path at which browsers look for an icon if a document declares none,
/// e.g., an image opened directly.
const FAVICON: &str = "/favicon.ico";

/// All files in `assets/` as `(name, content type, content)`, generated by
/// `build.rs`.
const FILES: &[(&str, &str, &[u8])] = include!(concat!(env!("OUT_DIR"), "/assets.rs"));

/// The embedded files with their URLs and precomputed responses.
#[derive(Debug)]
pub(crate) struct AssetCatalog {
    /// The hashed URL of each file by name.
    urls: HashMap<&'static str, String>,
    /// The responses by path, including the favicon.
    routes: Vec<(String, Arc<CachedResponse>)>,
}

impl AssetCatalog {
    /// Hashes and compresses all embedded files.
    pub(crate) fn new() -> Self {
        let mut urls = HashMap::new();
        let mut routes = Vec::new();
        for &(name, content_type, bytes) in FILES {
            let compression = if content_type.starts_with("text/") {
                Compression::Precompress
            } else {
                Compression::Never
            };
            let url = hashed_url(name, &content_hash(bytes));
            let response = |policy| {
                Arc::new(CachedResponse::new(
                    StatusCode::OK,
                    content_type,
                    policy,
                    bytes.to_vec(),
                    compression,
                ))
            };
            routes.push((url.clone(), response(CachePolicy::Immutable)));
            if name == ICON_32 {
                // The content behind this path may change, so it must be checked.
                routes.push((FAVICON.to_string(), response(CachePolicy::Revalidate)));
            }
            urls.insert(name, url);
        }
        Self { urls, routes }
    }

    /// Returns the hashed URL of the file `name`, e.g., `style.css`.
    ///
    /// # Panics
    ///
    /// Panics if there is no such file. The names are fixed in the code, and a
    /// test renders every page.
    pub(crate) fn url(&self, name: &str) -> &str {
        self.urls
            .get(name)
            .expect("asset names are fixed in the code, so they should be embedded")
    }

    /// Returns the hashed URL of the image that the WordPress site served at
    /// `path`, if there is one.
    pub(crate) fn legacy_image_url(&self, path: &str) -> Option<&str> {
        let file = path.strip_prefix(LEGACY_UPLOADS)?;
        if !file.ends_with(".png") {
            return None;
        }
        self.urls
            .get(format!("images/{file}").as_str())
            .map(String::as_str)
    }

    /// Returns all paths with their responses.
    pub(crate) fn routes(&self) -> impl Iterator<Item = (&str, &Arc<CachedResponse>)> {
        self.routes
            .iter()
            .map(|(path, response)| (path.as_str(), response))
    }
}

/// Inserts the hash before the extension: `a/b.css` becomes `/assets/a/b.HASH.css`.
fn hashed_url(name: &str, hash: &str) -> String {
    match name.rsplit_once('.') {
        Some((stem, extension)) => format!("/assets/{stem}.{hash}.{extension}"),
        None => format!("/assets/{name}.{hash}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The hash goes before the extension, so the type stays recognizable.
    #[test]
    fn hashed_url_keeps_extension() {
        assert_eq!(hashed_url("style.css", "abc"), "/assets/style.abc.css");
        assert_eq!(
            hashed_url("images/a.png", "abc"),
            "/assets/images/a.abc.png"
        );
        assert_eq!(hashed_url("LICENSE", "abc"), "/assets/LICENSE.abc");
    }

    /// Every file has a unique hashed URL with an immutable response.
    #[test]
    fn every_source_has_hashed_url() {
        let catalog = AssetCatalog::new();

        for &(name, _, bytes) in FILES {
            let url = catalog.url(name);
            let (_, response) = catalog
                .routes()
                .find(|(path, _)| *path == url)
                .expect("hashed URL should have a route");

            assert_eq!(response.body(), bytes);
        }
    }

    /// The old WordPress image URLs lead to the hashed URLs of the images.
    #[test]
    fn legacy_image_urls_lead_to_hashed_urls() {
        let catalog = AssetCatalog::new();
        let name = "Visitenkarte-Arztpraxis-Dirk-Schuster.png";

        assert_eq!(
            catalog.legacy_image_url(&format!("{LEGACY_UPLOADS}{name}")),
            Some(catalog.url(&format!("images/{name}")))
        );
        assert_eq!(
            catalog.legacy_image_url(&format!("{LEGACY_UPLOADS}gone.png")),
            None
        );
        assert_eq!(catalog.legacy_image_url("/images/logo.png"), None);
    }

    /// Only the favicon has a second path. Old image URLs redirect instead,
    /// so that each image has one URL.
    #[test]
    fn only_favicon_has_a_second_path() {
        let catalog = AssetCatalog::new();
        let paths: Vec<_> = catalog.routes().map(|(path, _)| path).collect();

        assert!(paths.contains(&FAVICON));
        assert!(!paths.iter().any(|path| path.starts_with(LEGACY_UPLOADS)));
    }

    /// The stylesheet and the scripts are minified: their comments, such as
    /// the license header, and the indentation are gone.
    #[test]
    fn text_is_minified() {
        for &(name, _, bytes) in FILES
            .iter()
            .filter(|(_, content_type, _)| content_type.starts_with("text/"))
        {
            let text = str::from_utf8(bytes).expect("text assets should be UTF-8");

            assert!(!text.contains("SPDX-License-Identifier"), "{name}");
            assert!(!text.contains("\n  "), "{name}");
        }
    }

    /// The names that the code uses refer to embedded files.
    #[test]
    fn named_assets_exist() {
        let catalog = AssetCatalog::new();

        for name in [
            STYLESHEET,
            EDITOR_SCRIPT,
            ANALYTICS_SCRIPT,
            LIVE_RELOAD_SCRIPT,
            ICON_32,
            ICON_180,
            ICON_192,
            ICON_270,
        ] {
            assert!(catalog.url(name).starts_with("/assets/"), "{name}");
        }
    }
}
